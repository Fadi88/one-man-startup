"""Generate each AI tool's native files from the tool-agnostic sources.

Sources (edit these):    agents/<name>.md, skills/<name>/SKILL.md, AGENTS.md
Generated (never edit):  .claude/agents/, .claude/skills/, CLAUDE.md,
                         .cursor/rules/, GEMINI.md

Codex and most other tools read AGENTS.md directly and need nothing generated.

    python tools/sync_adapters.py           write the files
    python tools/sync_adapters.py --check   exit 1 if any generated file is stale (TPL-6)

Model tiers map to each tool's models through project.toml [models.<tool>];
the defaults below are used when the table is absent. "inherit" leaves the
choice to whatever model the founder's session runs, which keeps the template
usable on any plan.
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "lib"))
import frontmatter  # noqa: E402

GENERATED = "Generated by tools/sync_adapters.py from {src}. Edit the source, not this file."

CLAUDE_TOOLS = {
    "read": ["Read", "Grep", "Glob"],
    "web": ["WebFetch", "WebSearch"],
    "run": ["Bash"],
    "check": ["Bash"],
    "edit": ["Edit", "Write"],
    "delegate": ["Agent"],
}
# TPL-42: an agent with check access and no run access may run only the template's checkers.
CHECK_ONLY_HOOK = [
    "hooks:",
    "  PreToolUse:",
    '    - matcher: "Bash"',
    "      hooks:",
    "        - type: command",
    '          command: "python tools/lib/check_only.py"',
]
DEFAULT_MODELS = {"claude": {"deep": "opus", "standard": "sonnet", "fast": "haiku"}}


def config() -> dict:
    return tomllib.loads((ROOT / "project.toml").read_text(encoding="utf-8"))


def agents() -> list[tuple[Path, dict, str]]:
    return [(p, *frontmatter.read(p)) for p in sorted((ROOT / "agents").glob("*.md"))]


def skills() -> list[tuple[Path, dict, str]]:
    return [(p, *frontmatter.read(p)) for p in sorted((ROOT / "skills").glob("*/SKILL.md"))]


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(cfg: dict) -> dict[Path, str]:
    out: dict[Path, str] = {}
    targets = cfg.get("tools", {}).get("targets", [])
    pointer = "@AGENTS.md\n"

    if "claude" in targets:
        models = {**DEFAULT_MODELS["claude"], **cfg.get("models", {}).get("claude", {})}
        out[ROOT / "CLAUDE.md"] = (
            f"<!-- {GENERATED.format(src='AGENTS.md')} -->\n{pointer}"
        )
        for path, fm, body in agents():
            tools = list(dict.fromkeys(t for cap in fm["access"] for t in CLAUDE_TOOLS[cap]))
            lines = [
                "---",
                f"name: {fm['name']}",
                f"description: {yaml_str(fm['description'])}",
                f"tools: {', '.join(tools)}",
            ]
            model = models.get(fm["tier"], "inherit")
            if model != "inherit":
                lines.append(f"model: {model}")
            if fm["skills"]:
                lines.append("skills:")
                lines += [f"  - {s}" for s in fm["skills"]]
            if "check" in fm["access"] and "run" not in fm["access"]:
                lines += CHECK_ONLY_HOOK
            lines += ["---", "", f"<!-- {GENERATED.format(src=rel(path))} -->", "", body.rstrip(), ""]
            out[ROOT / ".claude" / "agents" / f"{fm['name']}.md"] = "\n".join(lines)
        for path, fm, body in skills():
            lines = ["---", f"name: {fm['name']}", f"description: {yaml_str(fm['description'])}"]
            if fm.get("user_only"):
                lines.append("disable-model-invocation: true")
            lines += ["---", "", f"<!-- {GENERATED.format(src=rel(path))} -->", "", body.rstrip(), ""]
            out[ROOT / ".claude" / "skills" / fm["name"] / "SKILL.md"] = "\n".join(lines)

    if "gemini" in targets:
        out[ROOT / "GEMINI.md"] = f"<!-- {GENERATED.format(src='AGENTS.md')} -->\n{pointer}"

    if "cursor" in targets:
        for kind, items in (("agent", agents()), ("skill", skills())):
            for path, fm, body in items:
                lines = [
                    "---",
                    f"description: {yaml_str(fm['description'])}",
                    "alwaysApply: false",
                    "---",
                    "",
                    f"<!-- {GENERATED.format(src=rel(path))} -->",
                    "",
                    body.rstrip(),
                    "",
                ]
                out[ROOT / ".cursor" / "rules" / f"{kind}-{fm['name']}.mdc"] = "\n".join(lines)
    return out


def generated_dirs() -> list[Path]:
    return [ROOT / ".claude" / "agents", ROOT / ".claude" / "skills", ROOT / ".cursor" / "rules"]


def main(argv: list[str]) -> int:
    check = "--check" in argv
    want = build(config())
    stale = []
    for path, text in want.items():
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != text:
            stale.append(rel(path))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    orphans = [
        p for d in generated_dirs() if d.exists() for p in d.rglob("*") if p.is_file() and p not in want
    ]
    for pointer in (ROOT / "CLAUDE.md", ROOT / "GEMINI.md"):
        if pointer.exists() and pointer not in want and "Generated by tools/sync_adapters.py" in pointer.read_text(encoding="utf-8"):
            orphans.append(pointer)
    for p in orphans:
        stale.append(f"{rel(p)} (no source)")
        if not check:
            p.unlink()
    if check:
        for s in stale:
            print(f"FAIL  stale generated file: {s}, run python tools/sync_adapters.py")
        if not stale:
            print(f"PASS  {len(want)} generated files match their sources")
        return 1 if stale else 0
    print(f"wrote {len(stale)} of {len(want)} generated files" if stale else "all generated files current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
