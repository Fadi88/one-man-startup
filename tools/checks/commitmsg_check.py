"""TPL-7, TPL-75: the commit-msg hook refuses what it promises to refuse, and only that.

A hook nobody tests is a hook that silently passes everything. This runs the
real rule function against each refused form and each accepted one, with both
line endings.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "githooks"))
import commit_msg  # noqa: E402

CFG = {"style": {"banned_chars": ["\u2014", "\u2013"]}}

ROWS = {"REQ-12", "REQ-13", "TPL-41a"}

REFUSED = {
    "em dash": "REQ-12: add login \u2014 with email\n",
    "en dash": "REQ-12: pages 1\u20132\n",
    "no id": "Add login\n",
    "an id only in the body": "Add login\n\nFor REQ-12.\n",
    "an id after the colon": "Login: REQ-12\n",
    "an id that is not a row": "REQ-99: add login\n",
    "one unknown id among known": "REQ-12, REQ-99: add login\n",
}
ACCEPTED = {
    "a clean message": "REQ-12: add email login\n\nThe form validates on blur.\n",
    "several ids and a range": "REQ-12 to REQ-13, TPL-41a: add login\n",
    "a co-author trailer": "REQ-12: add login\n\nCo-authored-by: Claude <noreply@anthropic.com>\n",
    "a generated byline": "REQ-12: add login\n\nGenerated with Claude Code\n",
    "a session link": "REQ-12: add login\n\nhttps://claude.ai/code/session_123\n",
    "a comment line before the subject": "# Please enter the commit message\nREQ-12: add login\n",
    "a merge": "Merge branch 'main' into feature\n",
    "a revert": 'Revert "REQ-12: add login"\n',
    "a fixup": "fixup! REQ-12: add login\n",
}

failed = 0
for eol in ("\n", "\r\n"):
    for label, msg in REFUSED.items():
        if commit_msg.problems(msg.replace("\n", eol), CFG, ROWS):
            print(f"PASS  refuses {label} ({eol!r})")
        else:
            print(f"FAIL  lets through {label} ({eol!r})")
            failed += 1
    for label, msg in ACCEPTED.items():
        if commit_msg.problems(msg.replace("\n", eol), CFG, ROWS):
            print(f"FAIL  refuses {label} ({eol!r})")
            failed += 1
        else:
            print(f"PASS  accepts {label} ({eol!r})")

real = commit_msg.row_ids()
if "TPL-75" in real and len(real) > 50:
    print(f"PASS  reads {len(real)} row ids from docs/requirements/")
else:
    print("FAIL  row_ids() did not read the real requirement rows")
    failed += 1

sys.exit(1 if failed else 0)
