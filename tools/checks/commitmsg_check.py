"""TPL-7: the commit-msg hook refuses what it promises to refuse, and only that.

A hook nobody tests is a hook that silently passes everything. This runs the
real rule function against each refused form and a clean message, with both
line endings.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "githooks"))
import commit_msg  # noqa: E402

CFG = {"owner": {"name": "Founder", "email": "founder@example.com"}, "style": {"banned_chars": ["\u2014", "\u2013"]}}
GOOD_AUTHOR = "Founder <founder@example.com> 1700000000 +0000"

REFUSED = {
    "co-author trailer": "Add login\n\nCo-authored-by: Claude <noreply@anthropic.com>\n",
    "generated byline": "Add login\n\nGenerated with Claude Code\n",
    "session link": "Add login\n\nhttps://claude.ai/code/session_123\n",
    "em dash": "Add login \u2014 with email\n",
    "en dash": "Pages 1\u20132\n",
}

failed = 0
for eol in ("\n", "\r\n"):
    for label, msg in REFUSED.items():
        if commit_msg.problems(msg.replace("\n", eol), CFG, GOOD_AUTHOR):
            print(f"PASS  refuses {label} ({eol!r})")
        else:
            print(f"FAIL  lets through {label} ({eol!r})")
            failed += 1
    clean = "REQ-12: add email login\n\nThe form validates on blur.\n".replace("\n", eol)
    if commit_msg.problems(clean, CFG, GOOD_AUTHOR):
        print(f"FAIL  refuses a clean message ({eol!r})")
        failed += 1
    else:
        print(f"PASS  accepts a clean message ({eol!r})")

if commit_msg.problems("REQ-1: x\n", CFG, "Someone Else <other@example.com> 1 +0000"):
    print("PASS  refuses an author who is not the founder")
else:
    print("FAIL  accepts an author who is not the founder")
    failed += 1

if not commit_msg.problems("REQ-1: x\n", {"owner": {"email": "unset"}}, "Anyone <a@b.c> 1 +0000"):
    print("PASS  an unset owner does not block commits before setup has run")
else:
    print("FAIL  an unset owner blocks commits")
    failed += 1

sys.exit(1 if failed else 0)
